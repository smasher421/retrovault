-- RetroVault stores Steam OpenID IDs as text; it does not create Supabase Auth users.
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  user_id text not null,
  title text not null,
  platform text not null default 'Unknown',
  genre text,
  year integer,
  status text not null default 'Backlog'
    check (status in ('Backlog', 'Playing', 'Completed', '100% Completed', 'Abandoned')),
  notes text,
  cover_image text,
  created_at timestamptz not null default now(),
  steam_app_id bigint,
  playtime_minutes integer not null default 0,
  last_played_at timestamptz,
  source text not null default 'manual' check (source in ('manual', 'steam'))
);

alter table public.games add column if not exists steam_app_id bigint;
alter table public.games add column if not exists playtime_minutes integer not null default 0;
alter table public.games add column if not exists last_played_at timestamptz;
alter table public.games add column if not exists source text not null default 'manual';
create unique index if not exists games_user_steam_app_unique
  on public.games (user_id, steam_app_id);
create index if not exists games_user_created_idx on public.games (user_id, created_at desc);

alter table public.games enable row level security;
-- The app accesses this table only from its backend using the service role key.
-- Do not add anon/authenticated policies unless you switch to Supabase Auth JWTs.
revoke all on public.games from anon, authenticated;
grant all on public.games to service_role;
grant usage, select on all sequences in schema public to service_role;
