create extension if not exists pg_trgm with schema extensions;

create table if not exists public.profiles (
  steam_id text primary key check (steam_id ~ '^[0-9]{17}$'),
  username text not null default 'Steam user',
  avatar_url text,
  profile_url text,
  steam_created_at timestamptz,
  preferred_theme text not null default 'vgui-olive'
    check (preferred_theme in ('vgui-olive', 'source-obsidian', 'hev-hazard', 'lan-party-98')),
  custom_theme jsonb not null default '{}'::jsonb,
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.games_catalog (
  id bigint generated by default as identity primary key,
  catalog_key text not null unique,
  steam_app_id bigint unique,
  igdb_id bigint unique,
  rawg_id bigint unique,
  legacy_game_id bigint unique,
  title text not null,
  slug text,
  release_year integer,
  developer text,
  publisher text,
  summary text,
  genres text[] not null default '{}'::text[],
  platforms text[] not null default '{}'::text[],
  cover_url text,
  backdrop_url text,
  time_to_beat_hours numeric(7,2),
  rating_avg numeric(4,2) not null default 0,
  rating_count integer not null default 0,
  co_op boolean not null default false,
  multiplayer boolean not null default false,
  metadata_provider text not null default 'legacy',
  metadata_updated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint games_catalog_year_check check (release_year is null or release_year between 1950 and 2200),
  constraint games_catalog_rating_count_check check (rating_count >= 0),
  constraint games_catalog_rating_avg_check check (rating_avg between 0 and 10)
);

create table if not exists public.user_games (
  id bigint generated by default as identity primary key,
  user_id text not null references public.profiles(steam_id) on delete cascade,
  catalog_id bigint not null references public.games_catalog(id) on delete restrict,
  status text not null default 'Backlog'
    check (status in ('Backlog', 'Playing', 'Completed', '100% Completed', 'Abandoned')),
  rating smallint check (rating is null or rating between 1 and 10),
  platform_played text not null default 'PC',
  playtime_minutes integer not null default 0 check (playtime_minutes >= 0),
  last_played_at timestamptz,
  is_favorite boolean not null default false,
  notes text,
  review_text text,
  purchase_price numeric(10,2) check (purchase_price is null or purchase_price >= 0),
  source text not null default 'manual' check (source in ('manual', 'steam')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_games_user_catalog_unique unique (user_id, catalog_id)
);

create table if not exists public.play_logs (
  id bigint generated by default as identity primary key,
  user_id text not null references public.profiles(steam_id) on delete cascade,
  user_game_id bigint not null references public.user_games(id) on delete cascade,
  catalog_id bigint not null references public.games_catalog(id) on delete cascade,
  happened_at timestamptz not null default now(),
  source text not null default 'manual' check (source in ('manual', 'steam')),
  delta_minutes integer not null check (delta_minutes > 0),
  total_playtime_minutes integer,
  note text,
  created_at timestamptz not null default now(),
  constraint play_logs_user_game_total_unique unique (user_game_id, total_playtime_minutes)
);

create index if not exists games_catalog_title_trgm_idx
