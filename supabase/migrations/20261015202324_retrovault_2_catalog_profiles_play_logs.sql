  on public.play_logs (user_id, happened_at desc);

insert into public.profiles (steam_id, username)
select distinct user_id, 'Steam user'
from public.games
where user_id ~ '^[0-9]{17}$'
on conflict (steam_id) do nothing;

insert into public.games_catalog (
  catalog_key, steam_app_id, legacy_game_id, title, slug, release_year,
  genres, platforms, cover_url, backdrop_url, metadata_provider
)
select distinct on (steam_app_id)
  'steam:' || steam_app_id::text,
  steam_app_id,
  case when steam_app_id is null then id else null end,
  title,
  trim(both '-' from regexp_replace(lower(title), '[^a-z0-9]+', '-', 'g')),
  year,
  case when genre is null or genre = '' or genre = 'Unknown' then '{}'::text[] else array[genre] end,
  array[coalesce(nullif(platform, ''), 'Unknown')],
  nullif(cover_image, ''),
  nullif(cover_image, ''),
  'legacy'
from public.games
where steam_app_id is not null
order by steam_app_id, created_at desc
on conflict (steam_app_id) do nothing;

insert into public.games_catalog (
  catalog_key, legacy_game_id, title, slug, release_year, genres, platforms,
  cover_url, backdrop_url, metadata_provider
)
select
  'legacy:' || id::text,
  id,
  title,
  trim(both '-' from regexp_replace(lower(title), '[^a-z0-9]+', '-', 'g')),
  year,
  case when genre is null or genre = '' or genre = 'Unknown' then '{}'::text[] else array[genre] end,
  array[coalesce(nullif(platform, ''), 'Unknown')],
  nullif(cover_image, ''),
  nullif(cover_image, ''),
  'legacy'
from public.games
where steam_app_id is null
on conflict (legacy_game_id) do nothing;

insert into public.user_games (
  user_id, catalog_id, status, platform_played, playtime_minutes,
  last_played_at, notes, source, created_at
)
select
  g.user_id,
  c.id,
  coalesce(g.status, 'Backlog'),
  coalesce(nullif(g.platform, ''), 'PC'),
  coalesce(g.playtime_minutes, 0),
  g.last_played_at,
  g.notes,
  case when g.steam_app_id is null then 'manual' else 'steam' end,
  coalesce(g.created_at, now())
from public.games g
join public.games_catalog c
  on (g.steam_app_id is not null and c.steam_app_id = g.steam_app_id)
  or (g.steam_app_id is null and c.legacy_game_id = g.id)
on conflict (user_id, catalog_id) do nothing;

create or replace function public.recalculate_catalog_rating()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  target_catalog_id bigint;
begin
  if tg_op = 'DELETE' then
    target_catalog_id := old.catalog_id;
  else
    target_catalog_id := new.catalog_id;
  end if;

  update public.games_catalog
  set rating_avg = coalesce((
        select avg(rating)::numeric(4,2)
        from public.user_games
        where catalog_id = target_catalog_id and rating is not null
      ), 0),
      rating_count = (
        select count(*)::integer
        from public.user_games
        where catalog_id = target_catalog_id and rating is not null
      ),
      updated_at = now()
  where id = target_catalog_id;

  if tg_op = 'UPDATE' and old.catalog_id is distinct from new.catalog_id then
    update public.games_catalog
    set rating_avg = coalesce((
          select avg(rating)::numeric(4,2)
          from public.user_games
          where catalog_id = old.catalog_id and rating is not null
        ), 0),
        rating_count = (
          select count(*)::integer
          from public.user_games
          where catalog_id = old.catalog_id and rating is not null
        ),
        updated_at = now()
    where id = old.catalog_id;
  end if;

  return null;
end;
$$;

drop trigger if exists user_games_rating_rollup on public.user_games;
create trigger user_games_rating_rollup
after insert or update of rating, catalog_id or delete on public.user_games
for each row execute function public.recalculate_catalog_rating();

